"""Build src/data/emoji.js from Unicode's emoji-test.txt.

Usage: python3 -I scripts/build_emoji.py <path/to/emoji-test.txt> <max-emoji-version>

- keeps fully-qualified emojis only, no skin-tone variants, no components, no flags
- groups them into the iOS keyboard sections, in iOS order
- moves a few subgroups the way Apple does (approximation, see docs/05 §14)
"""
import json
import re
import sys

src, max_version = sys.argv[1], float(sys.argv[2])

SKIN = re.compile("[\U0001F3FB-\U0001F3FF]")
line_re = re.compile(r"^([0-9A-F ]+?)\s*;\s*fully-qualified\s*#\s*(\S+)\s+E(\d+\.\d+)\s+(.*)$")

# iOS sections, in keyboard order
SECTIONS = [
    ("smileys", "Smileys & People"),
    ("animals", "Animals & Nature"),
    ("food", "Food & Drink"),
    ("activity", "Activity"),
    ("travel", "Travel & Places"),
    ("objects", "Objects"),
    ("symbols", "Symbols"),
]  # no flags (D43)
GROUP_TO_SECTION = {
    "Smileys & Emotion": "smileys",
    "People & Body": "smileys",
    "Animals & Nature": "animals",
    "Food & Drink": "food",
    "Activities": "activity",
    "Travel & Places": "travel",
    "Objects": "objects",
    "Symbols": "symbols",
}
# Apple-style moves: subgroup -> (section, "start" | "end")
MOVES = {
    "heart": ("symbols", "start"),
    "clothing": ("smileys", "end"),
    "person-sport": ("activity", "end"),
    "sky & weather": ("animals", "end"),
}

buckets = {key: {"start": [], "main": [], "end": []} for key, _ in SECTIONS}
group = subgroup = None
with open(src, encoding="utf-8") as f:
    for line in f:
        if line.startswith("# group:"):
            group = line.split(":", 1)[1].strip()
            continue
        if line.startswith("# subgroup:"):
            subgroup = line.split(":", 1)[1].strip()
            continue
        m = line_re.match(line.strip())
        if not m or group not in GROUP_TO_SECTION:
            continue
        emoji, version, name = m.group(2), float(m.group(3)), m.group(4)
        if version > max_version or SKIN.search(emoji):
            continue
        section, where = MOVES.get(subgroup, (GROUP_TO_SECTION[group], "main"))
        buckets[section][where].append([emoji, subgroup, name])

out = []
for key, title in SECTIONS:
    b = buckets[key]
    items = b["start"] + b["main"] + b["end"]
    out.append({"key": key, "title": title, "emojis": items})

total = sum(len(s["emojis"]) for s in out)
with open("src/data/emoji.js", "w", encoding="utf-8") as f:
    f.write("// Generated by scripts/build_emoji.py from Unicode emoji-test.txt. Do not edit.\n")
    f.write(f"// {total} emojis, max Emoji version {max_version}, iOS section order.\n")
    f.write("// Each emoji: [emoji, subgroup, name]\n")
    f.write("export const SECTIONS = ")
    json.dump(out, f, ensure_ascii=False, separators=(",", ":"))
    f.write(";\n")
print(total, {s["key"]: len(s["emojis"]) for s in out})
